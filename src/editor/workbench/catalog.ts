export type WorkbenchCommandId = (typeof workbenchCommands)[number][0];
export const workbenchGroups = [...new Set(workbenchCommands.map((item) => item[2]))];
export function searchWorkbench(query: string, group = 'all') {
  const words = query.toLowerCase().trim().split(/\s+/).filter(Boolean);
  return workbenchCommands.filter(
    (command) =>
      (group === 'all' || command[2] === group) &&
      words.every((word) => command.join(' ').toLowerCase().includes(word)),
  );
}
