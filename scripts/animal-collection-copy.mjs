export function collectionCopy(topic, items) {
  const [lead, intro, links] = contexts[topic];
  const label = topic.replaceAll('-', ' ');
  const article = /^[aeiou]/.test(label) ? 'an' : 'a';
  const sizes = new Set(items.map((item) => `${item.width} × ${item.height}`));
  const printDetails =
    sizes.size === 1
      ? `Each illustration has a transparent ${items[0].width.toLocaleString('en-US')} × ${items[0].height.toLocaleString('en-US')} pixel WebP and a matching CMYK PDF approximately ${(items[0].width / 300).toFixed(2)} × ${(items[0].height / 300).toFixed(2)} inches.`
      : 'Each illustration has a transparent WebP and a matching CMYK PDF. Pixel dimensions and native print sizes vary by design; check the details on the individual artwork page.';
  const choose = (pattern) => items.find((item) => pattern.test(item.id));
  const realistic = choose(/realistic|classic|colored-pencil|standing/),
    decorative = choose(/floral|folk|wreath|mosaic|stained-glass/),
    outline = choose(/outline|coloring-page|cute-coloring/),
    watercolor = choose(/watercolor/);
  return {
    description: `Explore ${items.length} ${label} clipart designs for personal and classroom projects. Edit online and download matching transparent WebP or CMYK PDF files.`,
    lead,
    intro,
    featured: [
      ...new Set(
        [realistic, watercolor, decorative, outline, ...items]
          .filter(Boolean)
          .map((item) => item.id),
      ),
    ].slice(0, 6),
    chips: [
      { label: 'Watercolor', query: `${label} watercolor` },
      { label: 'Outline drawings', query: `${label} outline` },
      { label: 'Decorative designs', query: `${label} floral` },
    ],
    heading: `Choose ${article} ${label} illustration for your layout`,
    paragraphs: [
      `Start with the space available on your page. ${realistic ? `“${realistic.title}” provides a clear starting point for an animal picture card.` : 'A simple isolated pose provides a clear starting point for an animal picture card.'} Keep the subject large enough to recognize before adding a name, question or short caption. For a sequence of cards, use a consistent image size and leave a separate writing area.`,
      `${decorative ? `For a decorative card, look at “${decorative.title}”.` : 'For a decorative card, look at the colorful character compositions.'} Give patterned or textured areas room to breathe and avoid placing lettering over fine details. ${watercolor ? `“${watercolor.title}” offers a softer treatment; preview it over your chosen background to see the edges clearly.` : 'Preview the artwork over your chosen background to check its edges and contrast.'}`,
      `${outline ? `“${outline.title}” offers an alternative for a coloring or drawing activity.` : 'The monochrome options offer an alternative for a drawing activity.'} Open the design in the editor to move, resize, rotate or crop the image and add separate text and shape layers. Save the project if you want to revise your arrangement later.`,
    ],
    print: `${printDetails} Each supplied PDF places its image at 300 pixels per inch. Use WebP for a digital layout and PDF for printing; select actual size to retain that scale. Enlarging the artwork reduces its effective resolution. Check one print before making multiple copies.`,
    related: links.split(','),
  };
}
